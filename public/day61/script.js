      // --- DOM Elements ---
      const body = document.body;
      const audio = document.getElementById("audio-source");
      const songTitleSpan = document.getElementById("song-title");
      const playlistUl = document.getElementById("playlist");
      const moodTextH1 = document.getElementById("current-mood-text");
      const moodSelector = document.getElementById("mood-selector");
      const themeToggleButton = document.getElementById("theme-toggle");
      const navLinks = document.querySelectorAll(".nav-link[data-page]");
      const pages = document.querySelectorAll(".page-content");
      const randomMoodButton = document.getElementById("random-mood");

      let currentPlaylist = [];
      let currentTrackIndex = 0; 

      // --- Core Functions ---

      function loadSong(song) {
        audio.src = song.src;
        songTitleSpan.textContent = song.title;
        audio.load();
      }

      /**
       * Handles the visual theme and playlist change.
       * @param {string} mood - The mood key.
       */
      function changeMood(mood) {
        const data = MOOD_DATA[mood];
        if (!data) return;

        // 1. Apply Theme (CSS Class)
        // Remove only mood classes, keeping dark-mode if present
        body.classList.remove(
          "happy",
          "sad",
          "energetic",
          "relaxed",
          "angry",
          "focused",
          "tired",
          "neutral"
        );
        body.classList.add(mood);

        // 2. Update UI text
        moodTextH1.textContent = `Current Mood: ${data.text}`;

        // 3. Update Playlist and Player state
        currentPlaylist = data.playlist;
        console.log(currentPlaylist)
        loadSong(currentPlaylist[0]);        
        localStorage.setItem("lastMood", mood);
        }

        function nextTrack() {
                if (currentPlaylist.length === 0) return;
                currentTrackIndex = (currentTrackIndex + 1) % currentPlaylist.length;
                loadSong(currentPlaylist[currentTrackIndex]);
            }

        function prevTrack() {
            if (currentPlaylist.length === 0) return;
            currentTrackIndex = (currentTrackIndex - 1 + currentPlaylist.length) % currentPlaylist.length;
            loadSong(currentPlaylist[currentTrackIndex]);
        }
      /**
       * Handles the navigation between Player and Settings pages.
       * @param {string} pageId - 'player' or 'settings'.
       */
      function navigateTo(pageId) {
        pages.forEach((page) => {
          page.classList.remove("active");
        });
        navLinks.forEach((link) => {
          link.classList.remove("active");
        });

        document.getElementById(`${pageId}-page`).classList.add("active");
        document
          .querySelector(`[data-page="${pageId}"]`)
          .classList.add("active");

        // For visual effect, apply the "Settings" page background/theme
        if (pageId === "settings") {
          // The settings page uses the tired/dark theme visually as a default background
          body.classList.remove(
            "happy",
            "sad",
            "energetic",
            "relaxed",
            "angry",
            "tired",
            "neutral"
          );
          body.classList.add("tired");
        } else {
          // Revert to the last saved mood when navigating back to player
          changeMood(localStorage.getItem("lastMood") || "neutral");
        }
      }

      // --- Event Listeners ---

      // Mood Buttons Click
      moodSelector.addEventListener("click", (event) => {
        if (event.target.tagName === "BUTTON") {
          changeMood(event.target.dataset.mood);
        }
      });

      //forward & backward control
      document.getElementById("forward-track").addEventListener("click",nextTrack)
      document.getElementById("backward-track").addEventListener("click",prevTrack)

      // Random Mood Shuffle
      randomMoodButton.addEventListener("click", () => {
        const moods = Object.keys(MOOD_DATA);
        const randomMood = moods[Math.floor(Math.random() * moods.length)];
        changeMood(randomMood);
      });

      // Dark/Light Mode Toggle
      themeToggleButton.addEventListener("click", () => {
        body.classList.toggle("dark-mode");
        const isDarkMode = body.classList.contains("dark-mode");
        localStorage.setItem("isDarkMode", isDarkMode);
        themeToggleButton.innerHTML = isDarkMode
          ? '<i class="fas fa-sun"></i> Light Mode'
          : '<i class="fas fa-moon"></i> Dark Mode';
      });

      // Navigation Links
      navLinks.forEach((link) => {
        link.addEventListener("click", (e) => {
          if (link.dataset.page) {
            e.preventDefault();
            navigateTo(link.dataset.page);
          }
        });
      });

      // --- Initial Setup ---
      window.onload = () => {
        // 1. Load Last Saved Mood and Theme
        const lastMood = localStorage.getItem("lastMood") || "neutral";
        changeMood(lastMood);

        // 2. Load Dark Mode Toggle State
        const isDarkMode = localStorage.getItem("isDarkMode") === "true";
        if (isDarkMode) {
          body.classList.add("dark-mode");
          themeToggleButton.innerHTML = '<i class="fas fa-sun"></i> Light Mode';
        } else {
          themeToggleButton.innerHTML = '<i class="fas fa-moon"></i> Dark Mode';
        }

        // 4. Set initial page to Player
        navigateTo("player");
      };
    